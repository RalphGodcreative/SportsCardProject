CREATE TABLE bowman_search_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_type VARCHAR(10)  NOT NULL,
    player      VARCHAR(100),
    year        SMALLINT,
    set_name    VARCHAR(255),
    user_id     BIGINT,
    created_at  TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_bowman_search_type CHECK (search_type IN ('PLAYER', 'SET')),
    CONSTRAINT fk_bowman_search_user  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_bowman_search_created_at ON bowman_search_history (created_at);
CREATE INDEX idx_bowman_search_user       ON bowman_search_history (user_id);
